def render_files() -> str:
    manifest = load_manifest()
    if not manifest:
        return "No files downloaded yet."
    lines = [
        "| File | URL | License | Downloaded | Bytes | SHA-256 |",
        "|---|---|---|---|---|---|",
    ]
    for entry in sorted(manifest.values(), key=lambda item: item["file"]):
        lines.append(
            f"| `{entry['file']}` | {entry['url']} | {entry['license']} | {entry['downloaded']} "
            f"| {entry['bytes']:,} | `{entry['sha256']}` |"
        )
    return "\n".join(lines)


def render_build() -> str:
    stats_path = PROCESSED / "build_stats.json"
    if not stats_path.exists():
        return "Corpus not built yet."
    stats = json.loads(stats_path.read_text(encoding="utf-8"))
    lines = [
        "| Output | Rows |",
        "|---|---|",
        f"| `corpus.parquet` (patents) | {stats['patents']:,} |",
        f"| `chunks.parquet` (all) | {stats['chunks']:,} |",
    ]
    lines += [f"| chunks: `{k}` | {v:,} |" for k, v in sorted(stats["chunks_by_type"].items())]
    lines += [f"| patents: `{k}` | {v:,} |" for k, v in sorted(stats["patents_by_source"].items())]
    lines.append(f"| `demo/patents.jsonl` | {stats['demo_patents']:,} |")
    dropped = stats.get("dropped") or {}
    if dropped:
        lines += [f"| dropped: `{k}` | {v:,} |" for k, v in sorted(dropped.items())]
    demo = DATASET / "demo" / "patents.jsonl"
    if demo.exists():
        lines += ["", f"`dataset/demo/patents.jsonl` SHA-256: `{sha256_file(demo)}`"]
    return "\n".join(lines)


def main() -> None:
    manifest = load_manifest()
    has_pv = any(name.startswith("patentsview:") for name in manifest)
    status = "Corpus built from HUPD." if manifest else "No data downloaded yet."
    if not has_pv:
        status += "\n\n" + PATENTSVIEW_NOTE
    text = TEMPLATE.format(status=status, files=render_files(), build=render_build())
    (DATASET / "README.md").write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DATASET / 'README.md'}")


if __name__ == "__main__":
    main()
